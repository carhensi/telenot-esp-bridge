  const DICTS = { de: DE, en: EN };

  function interpolate(str, vars) {
    if (!vars) return str;
    return str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  }

export const I18N = {
    dicts: DICTS,
    make(lang) {
      const d = DICTS[lang] || DE;
      return (key, vars) => interpolate(d[key] != null ? d[key] : key, vars);
    },
  };
